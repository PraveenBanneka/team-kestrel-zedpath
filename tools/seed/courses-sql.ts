// Generates migrations/0005_course_institution.sql: the 121 courses and 20 institutions of 2025/26, so D1 rows can
// reference them with foreign keys (CR-002: senior invites name a course; SENIOR accounts name an institution through
// account.verified_for_letter, which already references institution). Source = the official Uni-Code list (handbook
// pages 142 to 148, data/ugc/2025-2026/unicodes.csv) with course names from the compiled rulebook, so D1 holds exactly
// the codes the API validates against. 0002 is already applied, so this is a new migration, never an edit of 0002.
// Run from the repo root:  node tools/seed/courses-sql.ts
import fs from 'node:fs';
import path from 'node:path';
import { readCsv } from './csv.ts';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const book = JSON.parse(fs.readFileSync(path.join(ROOT, 'worker', 'generated', 'rulebook-2025-2026.json'), 'utf8')) as {
  courses: Record<string, { name: string }>; generatedAt: string;
};
const rows = readCsv(path.join(ROOT, 'data', 'ugc', '2025-2026', 'unicodes.csv'));

// Institution kind, from the official names: two campuses belong to a parent university (the CHECK in 0001 requires
// the parent for a CAMPUS and forbids it otherwise); UCSC and the Swamy Vipulananda Institute are institutes (HEI).
const CAMPUS_PARENT: Record<string, string> = { S: 'A', W: 'H' };
const HEI = new Set(['T', 'Y']);

const institutions = new Map<string, string>();
const courses = new Set<string>();
for (const r of rows) {
  const uni = r.uni_code, letter = uni.slice(3), code = uni.slice(0, 3);
  if (!/^\d{3}[A-Z]$/.test(uni)) throw new Error(`bad Uni-Code ${uni}`);
  const prev = institutions.get(letter);
  if (prev && prev !== r.university) throw new Error(`letter ${letter} names two institutions`);
  institutions.set(letter, r.university);
  courses.add(code);
}
for (const code of courses) if (!book.courses[code]) throw new Error(`course ${code} missing from the rulebook`);
for (const [c, p] of Object.entries(CAMPUS_PARENT)) {
  if (!institutions.has(c) || !institutions.has(p)) throw new Error(`campus ${c} or parent ${p} not in the list`);
  if (!/CAMPUS/.test(institutions.get(c)!)) throw new Error(`${c} is not named as a campus`);
}
for (const [l, n] of institutions) if (/CAMPUS/.test(n) && !CAMPUS_PARENT[l]) throw new Error(`campus ${l} has no parent mapping`);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const kind = (l: string) => CAMPUS_PARENT[l] ? 'CAMPUS' : HEI.has(l) ? 'HEI' : 'UNIVERSITY';
const instRows = [...institutions].sort(([a], [b]) => (CAMPUS_PARENT[a] ? 1 : 0) - (CAMPUS_PARENT[b] ? 1 : 0) || a.localeCompare(b))
  .map(([l, n]) => `  (${q(l)}, ${q(n)}, '${kind(l)}', ${CAMPUS_PARENT[l] ? q(CAMPUS_PARENT[l]) : 'NULL'})`);
const courseRows = [...courses].sort().map(c => `  (${q(c)}, ${q(book.courses[c].name)})`);

const sql = `-- ZedPath D1 migration 0005: courses and institutions (CR-002).
-- GENERATED by tools/seed/courses-sql.ts from data/ugc/2025-2026/unicodes.csv (UGC handbook 2025/26, pp.142-148)
-- and the rulebook built ${book.generatedAt}. Do not edit by hand. Parents are listed before their campuses.

INSERT INTO institution (letter, name_en, kind, parent_letter) VALUES
${instRows.join(',\n')};

INSERT INTO course (course_code, name_en) VALUES
${courseRows.join(',\n')};
`;
const out = path.join(ROOT, 'migrations', '0005_course_institution.sql');
fs.writeFileSync(out, sql);
console.log(`wrote ${path.relative(ROOT, out)}: ${institutions.size} institutions, ${courses.size} courses`);
