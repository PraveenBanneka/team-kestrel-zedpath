// Generates migrations/0010_journey_avatars_rules.sql for CR-006 (Praveen 2026-10-11; designed in ZP-DOC-05, CR-006).
// The 255 offerings of 2025/26 come from the official Uni-Code list (handbook pages 142 to 148,
// data/ugc/2025-2026/unicodes.csv), the same source as 0005, so a followed course has a real foreign key.
// Run from the repo root:  node tools/seed/cr006-sql.ts
import fs from 'node:fs';
import path from 'node:path';
import { readCsv } from './csv.ts';

const ROOT = path.resolve(import.meta.dirname, '..', '..');
const rows = readCsv(path.join(ROOT, 'data', 'ugc', '2025-2026', 'unicodes.csv'));
const offerings = [...new Set(rows.map(r => r.uni_code))].sort();
for (const u of offerings) if (!/^\d{3}[A-Z]$/.test(u)) throw new Error(`bad Uni-Code ${u}`);
if (offerings.length !== 255) throw new Error(`expected 255 Uni-Codes, found ${offerings.length}`);

export const AVATARS = Array.from({ length: 12 }, (_, i) => `a${String(i + 1).padStart(2, '0')}`);
export const JOURNEY_STEPS = ['RESULTS', 'LIST', 'COMPARE', 'UGC_APPLY', 'UGC_ORDER', 'APTITUDE', 'UGC_SELECTION', 'UGC_REGISTER'];
const list = (xs: string[]) => xs.map(x => `'${x}'`).join(',');

const sql = `-- 0010: CR-006 (Praveen 2026-10-11): group rules accepted once per account, profile avatars, and the Journey saved on
-- the account (followed courses and notices, ticked steps). Designed in ZP-DOC-05, CR-006. Generated by
-- tools/seed/cr006-sql.ts; do not edit by hand.

-- 1. The 255 offerings of 2025/26 (handbook pp.142-148). 0001 defined OFFERING but left it empty; filling it lets a
--    followed course reference a real offering instead of a free-text code.
INSERT INTO offering (course_code, institution_letter) VALUES
${offerings.map(u => `  ('${u.slice(0, 3)}', '${u.slice(3)}')`).join(',\n')};

-- 2. Group rules: accepted once per account, not once per group. A fact about the account and a rules version, so it
--    is its own relation (one row per account per version accepted: a new version asks again and the history stays).
CREATE TABLE group_rules_acceptance (
  account_id     INTEGER NOT NULL REFERENCES account(account_id) ON DELETE CASCADE,
  rules_version  TEXT    NOT NULL CHECK (rules_version IN ('2026-10-11')),
  accepted_at    TEXT    NOT NULL,
  PRIMARY KEY (account_id, rules_version)
) STRICT, WITHOUT ROWID;
-- Carry over what members already accepted under 0009, at the time they first joined. group_member.rules_version is no
-- longer read or written (expand, then contract): it stays until this release is stable, so a rollback to the previous
-- version still works, and a later migration drops it.
INSERT OR IGNORE INTO group_rules_acceptance (account_id, rules_version, accepted_at)
  SELECT account_id, rules_version, min(joined_at) FROM group_member WHERE rules_version IS NOT NULL GROUP BY account_id, rules_version;

-- 3. Avatar: one preset picture per account (no photo upload). NULL = initials, the behaviour before CR-006.
ALTER TABLE account ADD COLUMN avatar TEXT CHECK (avatar IS NULL OR avatar IN (${list(AVATARS)}));

-- 4. Journey on the account (it lived only on the phone before CR-006).
-- 4a. Courses the student follows. Composite foreign key to OFFERING.
CREATE TABLE journey_course (
  account_id          INTEGER NOT NULL REFERENCES account(account_id) ON DELETE CASCADE,
  course_code         TEXT    NOT NULL,
  institution_letter  TEXT    NOT NULL,
  followed_at         TEXT    NOT NULL,
  PRIMARY KEY (account_id, course_code, institution_letter),
  FOREIGN KEY (course_code, institution_letter) REFERENCES offering(course_code, institution_letter)
) STRICT, WITHOUT ROWID;
-- 4b. Notices and other paths the student follows (Gazette exams, intakes). The route catalogue is curated read-model
--     data compiled into the Worker (ZP-DOC-05, read-model decision), so the id is checked by shape here and against
--     the catalogue by the Worker. applied_at = the student ticked "I applied"; the Worker allows it only once the
--     notice is open.
CREATE TABLE journey_notice (
  account_id   INTEGER NOT NULL REFERENCES account(account_id) ON DELETE CASCADE,
  route_id     TEXT    NOT NULL CHECK (length(route_id) = 4 AND route_id GLOB 'R[0-9][0-9][0-9]'),
  followed_at  TEXT    NOT NULL,
  applied_at   TEXT,
  CHECK (applied_at IS NULL OR applied_at >= followed_at),
  PRIMARY KEY (account_id, route_id)
) STRICT, WITHOUT ROWID;
-- 4c. Journey steps the student ticked. The step list is fixed (shared/journey.ts); a step can be ticked only once its
--     window is open, which the Worker checks against the dated read model before writing.
CREATE TABLE journey_step (
  account_id  INTEGER NOT NULL REFERENCES account(account_id) ON DELETE CASCADE,
  step_id     TEXT    NOT NULL CHECK (step_id IN (${list(JOURNEY_STEPS)})),
  done_at     TEXT    NOT NULL,
  PRIMARY KEY (account_id, step_id)
) STRICT, WITHOUT ROWID;
`;
fs.writeFileSync(path.join(ROOT, 'migrations', '0010_journey_avatars_rules.sql'), sql);
console.log(`wrote 0010 with ${offerings.length} offerings`);
